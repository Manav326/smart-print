import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const configPath = resolve(root, "config/upload-limits.json");
const limits = JSON.parse(readFileSync(configPath, "utf8"));

function positiveSafeInteger(name) {
  const value = limits[name];
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`upload-limits.json: ${name} must be a positive safe integer.`);
  }
  return value;
}

const maxFileBytes = positiveSafeInteger("maxFileBytes");
const maxBatchFiles = positiveSafeInteger("maxBatchFiles");
const maxBatchBytes = positiveSafeInteger("maxBatchBytes");
const multipartOverheadBytes = positiveSafeInteger("multipartOverheadBytes");
const privateRelayEncryptionOverheadBytes = positiveSafeInteger("privateRelayEncryptionOverheadBytes");

if (maxBatchFiles < 1 || maxBatchBytes < maxFileBytes) {
  throw new Error("Upload batch limits must allow at least one maximum-sized file.");
}
if (maxFileBytes + multipartOverheadBytes > Number.MAX_SAFE_INTEGER) {
  throw new Error("The multipart request limit exceeds the safe integer range.");
}

const maxMultipartRequestBytes = maxFileBytes + multipartOverheadBytes;
const outputs = new Map([
  ["src/SmartPrint.Api/Domain/UploadLimits.generated.cs", `// <auto-generated />
namespace SmartPrint.Api.Domain;

public static class UploadLimits
{
    public const long MaxFileBytes = ${maxFileBytes}L;
    public const int MaxBatchFiles = ${maxBatchFiles};
    public const long MaxBatchBytes = ${maxBatchBytes}L;
    public const long MaxMultipartRequestBytes = ${maxMultipartRequestBytes}L;
    public const long PrivateRelayEncryptionOverheadBytes = ${privateRelayEncryptionOverheadBytes}L;
}
`],
  ["src/SmartPrint.Agent/UploadLimits.generated.cs", `// <auto-generated />
namespace SmartPrint.Agent;

public static class UploadLimits
{
    public const long MaxFileBytes = ${maxFileBytes}L;
    public const int MaxBatchFiles = ${maxBatchFiles};
    public const long MaxBatchBytes = ${maxBatchBytes}L;
    public const long MaxMultipartRequestBytes = ${maxMultipartRequestBytes}L;
    public const long PrivateRelayEncryptionOverheadBytes = ${privateRelayEncryptionOverheadBytes}L;
}
`],
  ["apps/android/app/src/main/java/com/quantaedge/smartprint/UploadLimits.kt", `// Generated from config/upload-limits.json. Do not edit by hand.
package com.quantaedge.smartprint

internal object UploadLimits {
    const val MAX_FILE_BYTES: Long = ${maxFileBytes}L
    const val MAX_BATCH_FILES: Int = ${maxBatchFiles}
    const val MAX_BATCH_BYTES: Long = ${maxBatchBytes}L
    const val MAX_MULTIPART_REQUEST_BYTES: Long = ${maxMultipartRequestBytes}L
    const val PRIVATE_RELAY_ENCRYPTION_OVERHEAD_BYTES: Long = ${privateRelayEncryptionOverheadBytes}L
}
`],
  ["apps/portal/src/upload-limits.generated.ts", `// Generated from config/upload-limits.json. Do not edit by hand.
export const UPLOAD_LIMITS = Object.freeze({
  maxFileBytes: ${maxFileBytes},
  maxBatchFiles: ${maxBatchFiles},
  maxBatchBytes: ${maxBatchBytes},
  maxMultipartRequestBytes: ${maxMultipartRequestBytes},
  privateRelayEncryptionOverheadBytes: ${privateRelayEncryptionOverheadBytes}
} as const);
`]
]);

const checkOnly = process.argv.includes("--check");
let stale = false;
for (const [relativePath, content] of outputs) {
  const path = resolve(root, relativePath);
  let existing = null;
  try {
    existing = readFileSync(path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  if (existing === content) {
    process.stdout.write(`PASS ${relativePath}\n`);
    continue;
  }
  if (checkOnly) {
    stale = true;
    process.stderr.write(`STALE ${relativePath} — run pnpm generate:upload-limits\n`);
  } else {
    writeFileSync(path, content, "utf8");
    process.stdout.write(`GENERATED ${relativePath}\n`);
  }
}

if (stale) process.exitCode = 1;
