export function translateUiText(localeValue: unknown, sourceText: string, values: MessageValues = {}): string {
  const locale = normalizeUiLocale(localeValue);
  const template = screenTextCatalogs[locale][sourceText] ?? sourceText;
  return template.replace(/\\{([a-zA-Z][a-zA-Z0-9_]*)\\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export const DEFAULT_UI_LOCALE: UiLocale = (
  Object.entries(localeMetadata).find(([, metadata]) => metadata.default)?.[0] ?? "english"
) as UiLocale;

export const UI_LOCALE_OPTIONS = Object.entries(localeMetadata).map(([id, metadata]) => ({
  id: id as UiLocale,
  label: metadata.label,
  nativeLabel: metadata.nativeLabel,
  lang: metadata.lang,
}));

export function resolveUiLocale(value: unknown): UiLocale | null {
  const normalized = String(value ?? "").trim().toLowerCase();
  if (Object.prototype.hasOwnProperty.call(uiCatalogs, normalized)) return normalized as UiLocale;
  const match = Object.entries(localeMetadata).find(([, metadata]) =>
    metadata.aliases.some(alias => alias.toLowerCase() === normalized)
  );
  return match ? match[0] as UiLocale : null;
}

export function normalizeUiLocale(value: unknown): UiLocale {
  return resolveUiLocale(value) ?? DEFAULT_UI_LOCALE;
}

export function getUiLocaleLanguage(value: unknown): string {
  return localeMetadata[normalizeUiLocale(value)].lang;
}

export function getUiLocaleDirection(value: unknown): "ltr" | "rtl" {
  return localeMetadata[normalizeUiLocale(value)].dir;
}

export function translateUi(localeValue: unknown, key: keyof typeof english | string, values: MessageValues = {}): string {
  const locale = normalizeUiLocale(localeValue);
  const catalog = uiCatalogs[locale] as Record<string, string>;
  const fallbackLocale = localeMetadata[locale].fallback;
  const fallback = uiCatalogs[fallbackLocale] as Record<string, string>;
  const template = catalog[key] ?? fallback[key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export const UI_MESSAGE_KEYS = Object.keys(english) as Array<keyof typeof english>;

export function hasUiTranslation(key: string, localeValue: unknown): boolean {
  const locale = normalizeUiLocale(localeValue);
  return Object.prototype.hasOwnProperty.call(uiCatalogs[locale], key) || Object.prototype.hasOwnProperty.call(uiCatalogs[localeMetadata[locale].fallback], key);
}

export function translateUiPlural(
  localeValue: unknown,
  keyPrefix: string,
  count: number,
  values: MessageValues = {},
): string {
  const locale = normalizeUiLocale(localeValue);
  const category = new Intl.PluralRules(getUiLocaleLanguage(locale)).select(count);
  const key = keyPrefix + "." + category;
  const selectedKey = hasUiTranslation(key, locale) ? key : keyPrefix + ".other";
  return translateUi(locale, selectedKey, { ...values, count });
}

export function formatUiNumber(value: number, localeValue: unknown, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(getUiLocaleLanguage(localeValue), options).format(value);
}

export function formatUiDate(value: Date | number | string, localeValue: unknown, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(getUiLocaleLanguage(localeValue), options).format(new Date(value));
}

export function formatUiCurrency(value: number, localeValue: unknown, currency = "INR"): string {
  return new Intl.NumberFormat(getUiLocaleLanguage(localeValue), { style: "currency", currency }).format(value);
}
