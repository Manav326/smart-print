export interface PrinterDiagnosticArtworkProfile {
  displayName: string;
  queueName: string;
  connectionType: string;
  outputMode: string;
  templateVersion: string;
  paperSize: string;
  colourMode: string;
  isDuplex: boolean;
  pageCount: number;
  capabilityEvidence: string;
}

const PAGE_WIDTH = 1240;
const PAGE_HEIGHT = 1754;
const INK = "#172033";
const MUTED = "#586174";
const LINE = "#CDD3DF";
const VIOLET = "#6547D6";

function roundedRect(
  context: CanvasRenderingContext2D,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number
) {
  context.beginPath();
  context.roundRect(x, y, width, height, radius);
}

function drawText(
  context: CanvasRenderingContext2D,
  value: string,
  x: number,
  y: number,
  size: number,
  weight = 400,
  color = INK,
  align: CanvasTextAlign = "left"
) {
  context.font = `${weight} ${size}px Arial, "Noto Sans Devanagari", "Segoe UI", sans-serif`;
  context.fillStyle = color;
  context.textAlign = align;
  context.textBaseline = "alphabetic";
  context.fillText(value, x, y);
}

async function loadOfficialLogo(): Promise<HTMLImageElement | null> {
  try {
    const response = await fetch("/branding/smartprint-logo-light.svg", { cache: "force-cache" });
    if (!response.ok) return null;
    const svg = await response.text();
    if (!svg.includes("<svg") || svg.length > 100_000) return null;
    const blob = new Blob([svg], { type: "image/svg+xml" });
    const url = URL.createObjectURL(blob);
    try {
      const image = new Image();
      image.src = url;
      await image.decode();
      return image;
    } finally {
      URL.revokeObjectURL(url);
    }
  } catch {
    return null;
  }
}

function drawHeader(
  context: CanvasRenderingContext2D,
  logo: HTMLImageElement | null,
  pageNumber: number,
  totalPages: number
) {
  if (logo) context.drawImage(logo, 74, 42, 295, 81);
  else {
    drawText(context, "SmartPrint", 78, 105, 48, 800, VIOLET);
    drawText(context, "by QuantaEdge", 80, 137, 19, 600, MUTED);
  }

  roundedRect(context, 865, 52, 300, 60, 16);
  context.fillStyle = "#F1EDFF";
  context.fill();
  drawText(context, "PRINTER DIAGNOSTIC", 1015, 91, 22, 800, VIOLET, "center");

  context.strokeStyle = LINE;
  context.lineWidth = 2;
  context.beginPath();
  context.moveTo(74, 151);
  context.lineTo(1166, 151);
  context.stroke();

  drawText(context, `TEST PAGE ${pageNumber} OF ${totalPages}`, 1165, 183, 16, 700, MUTED, "right");
}

function drawFooter(context: CanvasRenderingContext2D, profile: PrinterDiagnosticArtworkProfile) {
  context.strokeStyle = LINE;
  context.lineWidth = 2;
  context.beginPath();
  context.moveTo(74, 1666);
  context.lineTo(1166, 1666);
  context.stroke();
  drawText(context, "Generated by SmartPrint · One diagnostic copy only", 74, 1703, 16, 600, MUTED);
  drawText(context, `${profile.paperSize} · ${profile.colourMode} · ${profile.isDuplex ? "Duplex" : "Simplex"}`, 1166, 1703, 16, 600, MUTED, "right");
}

function drawGeometry(context: CanvasRenderingContext2D, top: number) {
  const x = 105;
  const y = top;
  const width = 1030;
  const height = 380;
  context.save();
  context.strokeStyle = "#1D2533";
  context.lineWidth = 3;
  context.strokeRect(x, y, width, height);

  context.setLineDash([9, 8]);
  context.strokeStyle = "#8B93A3";
  context.lineWidth = 2;
  context.strokeRect(x + 42, y + 42, width - 84, height - 84);
  context.setLineDash([]);

  for (let index = 0; index <= 10; index++) {
    const markX = x + (width * index) / 10;
    const length = index % 5 === 0 ? 25 : 12;
    context.beginPath();
    context.moveTo(markX, y);
    context.lineTo(markX, y + length);
    context.moveTo(markX, y + height - length);
    context.lineTo(markX, y + height);
    context.stroke();
  }
  for (let index = 0; index <= 6; index++) {
    const markY = y + (height * index) / 6;
    const length = index % 3 === 0 ? 25 : 12;
    context.beginPath();
    context.moveTo(x, markY);
    context.lineTo(x + length, markY);
    context.moveTo(x + width - length, markY);
    context.lineTo(x + width, markY);
    context.stroke();
  }

  drawText(context, "PRINTABLE AREA / MARGIN CHECK", x + width / 2, y + 23, 15, 700, MUTED, "center");
  drawText(context, "EDGE / REGISTRATION REFERENCE", x + width / 2, y + height - 12, 14, 600, MUTED, "center");
  context.restore();
}

function drawGrayRamp(context: CanvasRenderingContext2D, top: number) {
  drawText(context, "MONOCHROME / GRAYSCALE", 105, top, 22, 800);
  const swatchY = top + 22;
  const gap = 6;
  const width = (1030 - gap * 7) / 8;
  for (let index = 0; index < 8; index++) {
    const value = Math.round(255 - (255 * index) / 7);
    context.fillStyle = `rgb(${value}, ${value}, ${value})`;
    context.fillRect(105 + index * (width + gap), swatchY, width, 74);
    context.strokeStyle = "#667085";
    context.lineWidth = 1;
    context.strokeRect(105 + index * (width + gap), swatchY, width, 74);
    drawText(context, String(value), 105 + index * (width + gap) + width / 2, swatchY + 99, 15, 600, MUTED, "center");
  }
}

function drawColorBars(context: CanvasRenderingContext2D, top: number) {
  drawText(context, "COLOUR SEPARATION / SOLID FILL", 105, top, 22, 800);
  const colours = ["#E53935", "#F9A825", "#43A047", "#00ACC1", "#1E5BDB", "#673AB7", "#EC407A", "#111827"];
  const gap = 8;
  const width = (1030 - gap * 7) / 8;
  colours.forEach((colour, index) => {
    context.fillStyle = colour;
    context.fillRect(105 + index * (width + gap), top + 20, width, 84);
    context.strokeStyle = "#586174";
    context.strokeRect(105 + index * (width + gap), top + 20, width, 84);
  });
}

function drawRegistrationMarks(context: CanvasRenderingContext2D, top: number) {
  drawText(context, "DUPLEX / BACK-SIDE REGISTRATION", 105, top, 22, 800);
  const marks = [
    [145, top + 105],
    [1095, top + 105],
    [145, top + 260],
    [1095, top + 260]
  ] as const;
  context.strokeStyle = "#171717";
  context.lineWidth = 3;
  for (const [x, y] of marks) {
    context.beginPath();
    context.arc(x, y, 20, 0, Math.PI * 2);
    context.moveTo(x - 32, y);
    context.lineTo(x + 32, y);
    context.moveTo(x, y - 32);
    context.lineTo(x, y + 32);
    context.stroke();
  }
  drawText(context, "TOP EDGE", 620, top + 80, 18, 700, MUTED, "center");
  drawText(context, "This is the reverse side of the same one-copy duplex test.", 620, top + 185, 20, 500, MUTED, "center");
  drawText(context, "Check front-to-back alignment and orientation.", 620, top + 222, 20, 500, MUTED, "center");
}

